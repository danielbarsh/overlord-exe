/** Mood AURA uses for each kind of roast */
export function moodFor(key: RoastKey): AuraMood {
  if (key === 'infiniteLoop' || key === 'divideByZero') return 'glitch';
  if (key === 'privateAccess') return 'angry';
  return 'laughing';
}

export function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function fill(tpl: string, extra: Record<string, string | undefined> = {}): string {
  return tpl.replace(/\{(\w+)\}/g, (m, k) => extra[k] ?? m);
}

export function roast(key: RoastKey, extra?: Record<string, string>): string {
  const extraFixed = { ...extra };
  if (key === 'casing' && !extraFixed.suggest) extraFixed.suggest = '?';
  if (key === 'unknownName' && extra?.staticCtx) {
    return fill('`{name}` לא סטטי, ואתה מנסה להשתמש בו מתוך `static`. צריך אובייקט (`new`) כדי לגשת אליו.', extraFixed);
  }
  if (key === 'unknownName' && (extra?.name === 'Robot' || extra?.name === 'Sensor')) {
    return fill('`{name}`? בשלב הזה הרובוט עוד לא מחובר ל-`{name}`. תקרא את התדריך — כאן עובדים רק עם מה שמופיע בו.', extraFixed);
  }
  if (key === 'unknownName' && extra?.suggest) {
    return fill('מה זה `{name}`? אין דבר כזה. אולי התכוונת ל-`{suggest}`? כתיב, חמוד, כתיב.', extraFixed);
  }
  if (key === 'syntax' && extra?.orphanElse) {
    return '`else` בלי `if` לפניו! ה-else יתום. בדוק שאין `;` או `}` מיותר בין ה-if ל-else.';
  }
  if (key === 'syntax' && extra?.declEq) {
    return 'בהצהרה על משתנה משתמשים ב-`=` אחד (השמה), לא `==`. דווקא כאן `==` הוא הטעות. איזה עולם הפוך.';
  }
  if (key === 'badStatement' && extra?.eq) {
    return 'כתבת `==` (השוואה) כשורה בפני עצמה. רצית לשים ערך? זה `=` אחד. רצית לבדוק? זה הולך בתוך `if (...)`.';
  }
  return fill(pick(ROASTS[key]), extraFixed);
}

